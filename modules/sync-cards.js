// 模式中文描述
function modeDesc(m) {
    if (m === 'anima') return 'anima 混合（Danbooru 标签定结构/构图 + 自然语言写光影/氛围/情绪）';
    if (m === 'anime') return 'anime（纯英文自然语言）';
    if (m === 'anime_tag') return 'anime_tag（纯 Danbooru 英文标签）';
    return 'zit（中文提示词）';
}

